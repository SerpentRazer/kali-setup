#!/bin/bash
# Reparatii de sistem gasite la inventarul de erori din 1 nov 2026 (dupa pasta noua). Fiecare pas are backup; revenire:
#   pkexec /bin/bash <folderul de backup afisat>/revino.sh
# Ruleaza: pkexec /bin/bash /home/mastermind/src/legion/fix-erori-root.sh
set -u
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
[ "$(id -u)" = 0 ] || { echo "Ruleaza cu pkexec."; exit 1; }
B=/home/mastermind/.config-backups/pre-fix-erori-root-$(date +%Y-%m-%d_%H-%M-%S); mkdir -p $B
ZR=/etc/udev/rules.d/30-zram.rules
GR=/etc/udev/rules.d/99-gpu-mgpu-floor.rules
SC=/etc/sysctl.d/70-cachy-bazzite.conf
SG=/etc/systemd/system-generators/systemd-sslh-generator
for f in $ZR $GR $SC /etc/default/locale /etc/locale.conf; do [ -f $f ] && cp -p $f $B/; done
cat > $B/revino.sh <<EOF
#!/bin/bash
# revine la starea dinainte de fix-erori-root.sh ($(date '+%F %T'))
[ "\$(id -u)" = 0 ] || { echo "Ruleaza cu pkexec."; exit 1; }
cp -p $B/30-zram.rules $ZR; cp -p $B/99-gpu-mgpu-floor.rules $GR; cp -p $B/70-cachy-bazzite.conf $SC
cp -p $B/locale /etc/default/locale; cp -p $B/locale.conf /etc/locale.conf
[ -L $SG ] && rm -f $SG
sysctl -w vm.swappiness=150; udevadm control --reload; systemctl daemon-reload
echo "revenit (limba: dupa relogin)"
EOF

echo "== 1. swappiness 150 -> 100"
# La pornirea CS2 kernelul a comprimat ~3 GB in zram in 47 s si a ramas fara memorie libera (page allocation failure 11:13:41),
# desi avea 6.3 GB de cache de fisiere aruncabil: cu 150 prefera sa comprime programe in loc sa arunce cache. 100 = echilibrat.
sed -i -e 's/SYSCTL{vm.swappiness}="150"/SYSCTL{vm.swappiness}="100"/' \
       -e 's/^# Din CachyOS-Settings: .*/# Din CachyOS-Settings (150), coborat la 100 pe 1 nov 2026: la pornirea CS2 kernelul comprima ~3 GB in zram in loc sa arunce cache-ul de fisiere -> sacadari./' $ZR
sed -i 's/^# swappiness=150 vine din/# swappiness=100 (era 150 pana la 1 nov 2026) vine din/' $SC
sysctl -w vm.swappiness=100
grep -o 'swappiness}="[0-9]*"' $ZR

echo "== 2. regula udev gpu-mgpu-floor fara eroare la boot"
# `systemctl is-active ... && ...` iesea cu 3 cat timp serviciul nu pornise inca (de 7 ori la fiecare boot) -> if/then = iesire 0
cat > $GR <<'EOF'
# Monitor conectat/deconectat (hotplug DRM) -> podeaua de frecventa GPU urmeaza starea. Vezi gpu-mgpu-floor.service.
# if/then (nu &&): la boot regula ruleaza inainte de serviciu si `is-active` iesea cu 3 = eroare falsa in jurnal (1 nov 2026).
ACTION=="change", SUBSYSTEM=="drm", ENV{HOTPLUG}=="1", RUN+="/bin/sh -c 'if systemctl is-active --quiet gpu-mgpu-floor.service; then /usr/local/sbin/gpu-mgpu-floor auto; fi; exit 0'"
EOF
udevadm control --reload && echo "reguli udev reincarcate"

echo "== 3. sslh: generatorul systemd crapa (SEGV) la fiecare boot"
# pachetul sslh e instalat dar nefolosit (serviciu disabled, /etc/sslh lipseste); mascam doar generatorul, pachetul ramane
mkdir -p /etc/systemd/system-generators && ln -sfn /dev/null $SG && ls -l $SG
systemctl daemon-reload && echo "daemon-reload fara SEGV: $(journalctl -b --since '-20s' -o cat | grep -c 'sslh-generator.*SEGV') aparitii noi"

echo "== 4. limba sesiunii: LANG=C.UTF-8 (acum gol -> Steam: XOpenIM failed, LANG = C)"
# C.UTF-8 = ce folosesc deja serviciile systemd; aceleasi formate ca acum (24h, punct zecimal), doar UTF-8. Efect dupa relogin.
update-locale LANG=C.UTF-8
printf '#  File generated by update-locale\nLANG=C.UTF-8\n' > /etc/locale.conf
grep -H LANG /etc/default/locale /etc/locale.conf

chown -R mastermind:mastermind $B
echo; echo "GATA. backup + revenire: pkexec /bin/bash $B/revino.sh"
